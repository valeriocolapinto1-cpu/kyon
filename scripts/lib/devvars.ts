import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { repoRoot } from './run';

export const devVarsPath = path.join(repoRoot, 'apps', 'web', '.dev.vars');

function randomSecret(bytes = 32): string {
  return Buffer.from(crypto.getRandomValues(new Uint8Array(bytes))).toString('base64url');
}

/** Creates apps/web/.dev.vars with random local secrets if missing. Returns the values. */
export function ensureDevVars(): Record<string, string> {
  const vars: Record<string, string> = {};
  if (existsSync(devVarsPath)) {
    for (const line of readFileSync(devVarsPath, 'utf8').split(/\r?\n/)) {
      const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
      if (match?.[1]) vars[match[1]] = match[2] ?? '';
    }
  }
  let changed = false;
  if (!vars.BETTER_AUTH_SECRET) {
    vars.BETTER_AUTH_SECRET = randomSecret();
    changed = true;
  }
  if (!vars.ADMIN_BOOTSTRAP_CODE) {
    vars.ADMIN_BOOTSTRAP_CODE = `kyon-${randomSecret(12)}`;
    changed = true;
  }
  if (!vars.TOKEN_ENCRYPTION_KEY) {
    vars.TOKEN_ENCRYPTION_KEY = Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString(
      'base64',
    );
    changed = true;
  }
  // No real GitHub App configured: use the fake GitHub that `pnpm dev` starts on :8799.
  if (!vars.GITHUB_APP_CLIENT_ID) {
    Object.assign(vars, {
      GITHUB_APP_CLIENT_ID: 'fake-dev-client',
      GITHUB_APP_CLIENT_SECRET: 'fake-dev-secret',
      GITHUB_APP_SLUG: 'kyon-dev',
      GITHUB_WEBHOOK_SECRET: 'fake-dev-webhook',
      GITHUB_API_URL: 'http://localhost:8799',
      GITHUB_WEB_URL: 'http://localhost:8799',
    });
    changed = true;
  }
  if (changed) {
    const body = Object.entries(vars)
      .map(([k, v]) => `${k}=${v}`)
      .join('\n');
    writeFileSync(
      devVarsPath,
      `# Local development only (gitignored). Generated by scripts/lib/devvars.ts.\n${body}\n`,
    );
  }
  return vars;
}
